const LOJA_VERIFIED_AT = "2026-08-20";

const PLACEHOLDER_IMG = (key: string) => `/placeholder/${key}.svg`;

/**
 * Raiz de /public, calculada a partir deste arquivo — para checar em disco
 * se já existe foto real baixada, sem depender do diretório de onde o
 * processo Node foi iniciado.
 */
const PUBLIC_DIR = join(process.cwd(), "public");

/**
 * Detecta foto REAL do produto em /public/produtos/<slug>/1.jpg, 2.jpg... —
 * pesquisada e baixada à parte (ver processo de importação de fotos).
 * Sem foto real ainda, cai na ilustração — nunca mistura as duas nem finge
 * que a ilustração é uma foto.
 */
function resolveImages(slug: string, name: string, fallbackKey: string): ProductImage[] {
  const dir = join(PUBLIC_DIR, "produtos", slug);
  const real: ProductImage[] = [];

  // `cover.webp` e a capa padronizada da vitrine. As fotos originais continuam
  // depois dela para preservar detalhes, informacoes e cenas de uso na galeria.
  const cover = join(dir, "cover.webp");
  if (existsSync(cover)) {
    real.push({ src: `/produtos/${slug}/cover.webp`, alt: `${name} — foto principal` });
  }
  // O catalogo de fotos enviado pelo dono tem prioridade na galeria. Arquivos
  // numerados preservam variacoes de cor sem apagar as fotos tecnicas atuais.
  for (let i = 1; i <= 6; i++) {
    const file = join(dir, `owner-${i}.webp`);
    if (!existsSync(file)) break;
    real.push({
      src: `/produtos/${slug}/owner-${i}.webp`,
      alt: `${name} — foto do catalogo Dom Guima ${i}`,
    });
  }
  for (let i = 1; i <= 6; i++) {
    const file = join(dir, `${i}.jpg`);
    if (!existsSync(file)) break;
    real.push({ src: `/produtos/${slug}/${i}.jpg`, alt: `${name} — foto ${i}` });
  }
  if (real.length > 0) return real;
  return [{ src: PLACEHOLDER_IMG(fallbackKey), alt: `${name} — imagem ilustrativa` }];
}

