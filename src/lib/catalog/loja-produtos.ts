const CATEGORY_PREFIX: Record<string, string> = {
  "smart-tvs": "TV",
  celulares: "CEL",
  eletrodomesticos: "ELD",
  climatizacao: "CLM",
  eletronicos: "ELT",
  informatica: "INF",
  ferramentas: "FER",
  "casa-decoracao": "CSA",
  beleza: "BLZ",
};

function buildLoja(d: LojaDraft, index: number): Product {
  const prefix = CATEGORY_PREFIX[d.categoryId] ?? "DG";
  const specifications: Specification[] = d.bullets.map((value, i) => ({
    label: `Destaque ${i + 1}`,
    value,
  }));
  if (d.color?.length) {
    specifications.push({ label: "Cor", value: d.color.join(", ") });
  }

  // Só vira variante SELECIONÁVEL quando há de fato mais de uma opção — uma
  // "escolha" com um único valor força um clique extra sem sentido (e some
  // com o botão "Adicionar ao carrinho" na vitrine à toa). Voltagem única
  // entra como especificação normal.
  const variants =
    d.voltage && d.voltage.length > 1
      ? [{ name: "Voltagem", options: d.voltage }]
      : undefined;
  if (d.voltage?.length === 1) {
    specifications.push({ label: "Voltagem", value: d.voltage[0] });
  }

  const slug = `${slugify(d.name)}-${index}`;

  return {
    id: `loja-${index}`,
    name: d.name,
    slug,
    description: d.bullets.slice(0, 2).join(". ") + ".",
    price: d.price,
    categoryId: d.categoryId,
    brand: d.brand,
    sku: `DG-${prefix}-${String(index + 1).padStart(3, "0")}`,
    stock: 5,
    images: resolveImages(slug, d.name, d.img),
    variants,
    specifications,
    shipping: {
      weight: d.weight,
      dimensions: { length: d.dims[0], width: d.dims[1], height: d.dims[2] },
      origin: "Minas Gerais",
    },
    isFeatured: false,
    isBestSeller: false,
    isOffer: false,
    isExclusive: Boolean(d.exclusive),
    tags: d.name
      .toLowerCase()
      .split(/\s+/)
      .filter((w) => w.length > 3)
      .slice(0, 8),
    dataSource: "loja-verified",
    cardInstallment: { count: d.card[0], value: d.card[1] },
    sellerNote: d.note,
  };
}

function slugify(name: string): string {
  return name
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 70);
}

export const lojaProducts: Product[] = drafts.map(buildLoja);
