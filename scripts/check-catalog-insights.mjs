import assert from "node:assert/strict";
import { createJiti } from "jiti";
const jiti = createJiti(import.meta.url);
const { recentUnits, stockCoverage, incompleteProduct, missingProductCost } = await jiti.import("../src/lib/admin/catalog-insights.ts");
const { validOfferDate, offerIsScheduledNow, readOfferSchedule } = await jiti.import("../src/lib/catalog/offer-schedule.ts");
const now = new Date("2026-11-13T15:00:00Z");
const order = (created_at, status = "completed", quantity = 2, variant_id = "blue") => ({ created_at, status, items: [{ product_id: "p1", variant_id, quantity }] });
const sold = recentUnits([order("2026-10-15T03:00:00Z"), order("2026-10-15T02:59:59Z"), order("2026-11-13T14:00:00Z", "completed", 3), order("2026-11-13T14:00:00Z", "pending", 90), order("2026-11-13T14:00:00Z", "cancelled", 90), order("2026-11-13T16:00:00Z"), order("invalid")], now);
assert.equal(sold.get("p1"), 5, "30 local days, boundary included, future/cancelled/pending excluded");
assert.equal(sold.get("p1::blue"), 5, "variant and aggregate product tracked separately");
assert.equal(recentUnits([order("2026-11-13T14:00:00Z", "completed", 2, null)], now).has("p1::null"), false);
assert.deepEqual(stockCoverage(5,30), { days: 5, replenish: 25 });
assert.equal(stockCoverage(0,0), null, "no sales means no invented forecast");
assert.deepEqual(stockCoverage(50,30), { days: 50, replenish: 0 });
assert.equal(validOfferDate("2026-02-30"), false);
assert.equal(validOfferDate("2024-02-29"), true);
assert.equal(validOfferDate(""), true);
assert.equal(offerIsScheduledNow({ starts: "2026-11-13", ends: "2026-11-13" }, now), true, "end date inclusive");
assert.equal(offerIsScheduledNow({ starts: "2026-11-14", ends: "" }, now), false);
assert.equal(offerIsScheduledNow({ starts: "", ends: "2026-11-12" }, now), false);
assert.equal(offerIsScheduledNow({ starts: "2026-11-13", ends: "" }, new Date("2026-11-13T02:59:59Z")), false, "São Paulo midnight");
assert.equal(offerIsScheduledNow(readOfferSchedule(undefined), now), true, "legacy offers unchanged");
assert.deepEqual(readOfferSchedule({ offer_schedule: { starts: "bad", ends: "bad" } }), { starts: "", ends: "" });
const product = { name: "Produto", sku: "P1", description: "Descrição", price_cents: 1000, product_images: [{ src: "/photo.png" }] };
assert.equal(incompleteProduct(product), false);
assert.equal(incompleteProduct({ ...product, sku: "" }), true);
assert.equal(missingProductCost(product, { cost_cents: 800 }), false);
assert.equal(missingProductCost({ ...product, product_variants: [{ id: "blue", active: true }] }, { cost_cents: 800 }), true, "base cost does not substitute variant cost");
assert.equal(missingProductCost({ ...product, product_variants: [{ id: "blue", active: true }] }, { variant_prices: { blue: { cost_cents: 800 } } }), false);
const { comparisonGroup } = await jiti.import("../src/lib/catalog/comparison.ts");
assert.notEqual(comparisonGroup("Soundbar Samsung", "tv"), comparisonGroup("Smart TV Samsung", "tv"));
assert.equal(comparisonGroup("Suporte para TV", "tv"), null);
assert.equal(comparisonGroup("Geladeira Electrolux", "eletro"), comparisonGroup("Refrigerador Brastemp", "eletro"));
console.log("catalog insights ok: local date range, variants, coverage, offer schedule, filters");
