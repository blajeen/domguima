import assert from "node:assert/strict";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const jiti = createJiti(import.meta.url, { alias: { "@": path.join(root, "src") } });
const { orderInput } = await jiti.import(path.join(root, "src/lib/admin/crm-order-input.ts"));
const { auditSummary } = await jiti.import(path.join(root, "src/lib/admin/audit-summary.ts"));
const { isOverdue } = await jiti.import(path.join(root, "src/lib/admin/crm-workflow-types.ts"));
const { signTrackingToken, verifyTrackingToken } = await jiti.import(path.join(root, "src/lib/admin/tracking-tokens.ts"));
const base = { requestId: "test-order-12345", sellerId: "gabriel", customer: { name: "Cliente teste", cpf: "", phone: "", cep: "", street: "", number: "", complement: "", neighborhood: "", city: "", state: "" }, notes: "", channel: "store", source: "store", items: [{ productId: "produto", quantity: 1, expectedStock: 2, unitPriceCents: 10000 }] };
assert.equal(orderInput.safeParse({ ...base, saleMode: "counter" }).success, true, "counter sale does not require address or document");
assert.equal(orderInput.safeParse(base).success, false, "old payload still defaults to delivery and requires address");
assert.equal(orderInput.safeParse({ ...base, saleMode: "delivery" }).success, false);
assert.equal(orderInput.safeParse({ ...base, saleMode: "counter", customer: { ...base.customer, cpf: "12345678900" } }).success, false, "invalid document is rejected even in counter mode");
const delivery = { ...base, customer: { ...base.customer, cpf: "52998224725", cep: "38400000", street: "Rua teste", number: "10", neighborhood: "Centro", city: "Uberlândia", state: "mg" } };
assert.equal(orderInput.parse(delivery).customer.state, "MG", "existing delivery flow preserved");
assert.equal(orderInput.safeParse({ ...base, saleMode: "counter", items: [] }).success, false, "counter keeps item validation");
assert.equal(auditSummary({ stock: 5 }, { stock: 3 }), "Estoque: 5 → 3");
assert.match(auditSummary({ price_cents: 10000 }, { price_cents: 12000 }), /100,00.*120,00/);
assert.equal(auditSummary(null, null), "—");
const now = new Date("2026-11-13T15:00:00Z");
assert.equal(isOverdue("2026-11-13T14:59:00Z", now), true);
assert.equal(isOverdue("2026-11-13T15:01:00Z", now), false);
assert.equal(isOverdue("invalid", now), false);
assert.equal(isOverdue(null, now), false);
const id = "a18e8cf2-98d4-4c72-a579-1ec828ff5478", secret = "test-secret-".repeat(5);
const token = await signTrackingToken(id, secret, now);
assert.equal(await verifyTrackingToken(token, secret, now), id);
assert.equal(await verifyTrackingToken(token, secret, new Date("2026-12-14T15:00:00Z")), null, "tracking links expire");
assert.equal(await verifyTrackingToken(token, "different-secret-".repeat(4), now), null);
assert.equal(await verifyTrackingToken(`${token.slice(0, -8)}tampered`, secret, now), null);
assert.equal(await verifyTrackingToken(token, "short", now), null);
assert.equal(await verifyTrackingToken("bad", secret, now), null);
console.log("crm ok: counter/delivery validation, human audit, followups and signed expiring tracking links");
