import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const temporary = mkdtempSync(path.join(tmpdir(), "dom-business-"));
const cwd = process.cwd();
const env = { ...process.env };
try {
  writeFileSync(path.join(temporary, "server-only.cjs"), "");
  process.chdir(temporary);
  delete process.env.SUPABASE_URL; delete process.env.SUPABASE_SECRET_KEY; delete process.env.SUPABASE_SERVICE_ROLE_KEY; delete process.env.VERCEL;
  const jiti = createJiti(path.join(root, "x.js"), { alias: { "@": path.join(root, "src"), "server-only": path.join(temporary, "server-only.cjs") } });
  const { marginSummary, emptyBusinessSettings, campaignInvestment, validMoney } = await jiti.import(path.join(root, "src/lib/admin/business-insights.ts"));
  const settings = emptyBusinessSettings();
  const item = (cost, revenue = 1000, quantity = 1) => ({ product_id: "p", product_name: "Teste", quantity, line_total_cents: revenue, commission_total_cents: 100, cost_unit_cents: cost });
  const order = (items, status = "completed") => ({ id: "a", status, items, seller_id: "s", seller_name: "Atendente", channel: "whatsapp", total_cents: items.reduce((sum, row) => sum + row.line_total_cents, 0) });
  const summary = marginSummary([order([item(200, 2000, 2), item(null)]), order([item(1)], "pending"), order([item(1)], "cancelled")]);
  assert.equal(summary.knownUnits, 2); assert.equal(summary.totalUnits, 3); assert.equal(summary.marginCents, 1500); assert.equal(summary.coveredSalesCents, 2000);
  assert.equal(summary.products[0].knownUnits, 2);
  assert.equal(marginSummary([order([item(0)])]).marginCents, 900, "explicit zero cost counts as known");
  settings.orderCosts.a = { items: { "0": 400 }, feesCents: 1, shippingCents: 100 };
  const withFees = marginSummary([order([item(200, 1000), item(200, 1000)])], settings);
  assert.equal(withFees.costCents, 600, "manual correction applies only to selected order item");
  assert.equal(withFees.marginCents, 1099, "fee allocation preserves exact cents across items");
  settings.campaignBudgets.x = { campaign: "teste", from: "2026-11-01", to: "2026-11-10", cents: 5000 };
  assert.equal(campaignInvestment(settings, "teste", "2026-11-01", "2026-11-13"), 5000);
  assert.equal(campaignInvestment(settings, "teste", "2026-11-05", "2026-11-13"), 0, "partial spend intervals never guessed");
  assert.equal(validMoney(NaN), false); assert.equal(validMoney(-1), false); assert.equal(validMoney(1.5), false);
  const { createInitialState, writeCatalogState, readCatalogState } = await jiti.import(path.join(root, "src/lib/admin/catalog-store.ts"));
  const { createSalesOrder } = await jiti.import(path.join(root, "src/lib/admin/orders.ts"));
  const state = createInitialState(); const product = state.products[0]; product.stock = 10; product.product_variants = [];
  state.operations.product_meta[product.id] = { ncm: "", model: "", gtin: "", cost_cents: 700 };
  state.operations.business = settings;
  state.operations.crm_workflow = { "order:a": { payment_status: "paid", updated_at: new Date().toISOString(), updated_by: "test" } };
  await writeCatalogState(state);
  const input = { requestId: "test-snapshot-001", sellerId: state.operations.sellers.find(seller => seller.active).id, customer: { name: "Cliente teste", cpf: "", phone: "", cep: "", street: "", number: "", complement: "", neighborhood: "", city: "", state: "" }, notes: "", channel: "store", source: "store", saleMode: "counter", items: [{ productId: product.id, quantity: 1, expectedStock: 10, unitPriceCents: product.price_cents }] };
  const created = await createSalesOrder(state, input, "test");
  assert.equal(created.items[0].cost_unit_cents, 700, "cost captured server-side in order JSON");
  const reread = await readCatalogState(true);
  assert.equal(reread.products.find(row => row.id === product.id).stock, 9);
  assert.equal(reread.operations.orders[0].items[0].cost_unit_cents, 700);
  assert.equal(reread.operations.crm_workflow["order:a"].payment_status, "paid", "normalization retains CRM annotations");
  assert.equal(reread.operations.business.campaignBudgets.x.cents, 5000, "normalization retains business settings");
  state.operations.product_meta[product.id].cost_cents = 900;
  assert.equal(created.items[0].cost_unit_cents, 700, "catalog cost changes cannot rewrite old cost");
  const retry = await createSalesOrder(reread, input, "test");
  assert.equal(retry.id, created.id); assert.equal((await readCatalogState(true)).products.find(row => row.id === product.id).stock, 9, "retry never lowers stock twice");
  console.log("business ok: historical gaps, zero cost, fee cents, attribution periods, persisted cost snapshots, metadata and stock/idempotency");
} finally {
  process.chdir(cwd); process.env = env; rmSync(temporary, { recursive: true, force: true });
}
